import { ExternalLink, FileCode, GitBranch } from 'lucide-react';
import type { GithubSecretEvidence } from './githubEvidence';

const SEVERITY_BADGE: Record<string, string> = {
  CRITICAL: 'badge-danger', HIGH: 'badge-danger', MEDIUM: 'badge-warning',
  LOW: 'badge-info', INFO: 'badge-info',
};

export function SecretExposureCard({ evidence }: { evidence: GithubSecretEvidence }) {
  return (
    <article className="ws-secret-card" data-testid="github-secret-card">
      <div className="ws-secret-header">
        <span className="ws-secret-type">{evidence.secretType}</span>
        <span className={`badge ${SEVERITY_BADGE[evidence.severity] || 'badge-info'}`}>{evidence.severity}</span>
        <span className="ws-secret-confidence">{Math.round(evidence.confidence * 100)}% confidence</span>
      </div>
      <div className="ws-secret-repo font-mono">
        <GitBranch size={14} />
        {evidence.repoUrl
          ? <a href={evidence.repoUrl} target="_blank" rel="noreferrer">{evidence.repoName}</a>
          : <span>{evidence.repoName}</span>}
      </div>
      <div className="ws-secret-file font-mono">
        <FileCode size={13} />
        <span title={evidence.filePath}>{evidence.filePath}</span>
      </div>
      <div className="ws-secret-signals">
        <span>Proximity: {evidence.proximity}</span>
        {evidence.autoGenerated && <span>Automated publisher</span>}
        {!evidence.classifierVersion && <span>Legacy scoring</span>}
        <span>Source: {evidence.source.replaceAll('_', ' ')}</span>
      </div>
      {evidence.fileUrl && (
        <a href={evidence.fileUrl} target="_blank" rel="noreferrer" className="ws-secret-link">
          Inspect public evidence <ExternalLink size={12} />
        </a>
      )}
    </article>
  );
}

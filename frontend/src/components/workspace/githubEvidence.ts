import type { Finding, Severity } from '../../types/api';

export interface GithubSecretEvidence {
  id: string;
  repoName: string;
  repoUrl?: string;
  filePath: string;
  fileUrl?: string;
  secretType: string;
  severity: Severity;
  confidence: number;
  proximity: string;
  autoGenerated: boolean;
  classifierVersion?: number;
  source: string;
}

export interface GithubRepositoryEvidence {
  id: string;
  repoName: string;
  repoUrl?: string;
  description: string;
  language: string;
  stars: number;
  searchStrategy?: string;
}

function text(value: unknown, fallback = ''): string {
  return typeof value === 'string' && value.trim() ? value.trim() : fallback;
}

function safeGithubUrl(value: unknown): string | undefined {
  if (typeof value !== 'string') return undefined;
  try {
    const url = new URL(value);
    return url.protocol === 'https:' && url.hostname.toLowerCase() === 'github.com'
      ? url.toString()
      : undefined;
  } catch {
    return undefined;
  }
}

export function toGithubSecret(finding: Finding): GithubSecretEvidence {
  const data = finding.normalized_data ?? {};
  const repoUrl = safeGithubUrl(data.repo_url);
  return {
    id: finding.id,
    repoName: text(data.repo_name, repoUrl?.replace('https://github.com/', '').replace(/\/$/, '') || 'Unknown repository'),
    repoUrl,
    filePath: text(data.file_path, 'Path unavailable'),
    fileUrl: safeGithubUrl(data.file_url),
    secretType: text(data.secret_type, 'UNKNOWN_SECRET'),
    severity: finding.severity,
    confidence: finding.confidence,
    proximity: text(data.domain_proximity, 'unknown'),
    autoGenerated: data.auto_generated === true,
    classifierVersion: Number.isFinite(Number(data.classifier_version)) ? Number(data.classifier_version) : undefined,
    source: finding.source_module,
  };
}

export function toGithubRepository(finding: Finding): GithubRepositoryEvidence {
  const data = finding.normalized_data ?? {};
  const repoUrl = safeGithubUrl(data.repo_url ?? finding.entity_value);
  const stars = Number(data.stars);
  return {
    id: finding.id,
    repoName: text(data.repo_name, repoUrl?.replace('https://github.com/', '').replace(/\/$/, '') || 'Unknown repository'),
    repoUrl,
    description: text(data.description),
    language: text(data.language, '—'),
    stars: Number.isFinite(stars) && stars >= 0 ? stars : 0,
    searchStrategy: text(data.search_strategy) || undefined,
  };
}
